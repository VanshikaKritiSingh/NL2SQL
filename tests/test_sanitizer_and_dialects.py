def testDescribeExplainUsePragmaStatementsAllowed():
    from core.validator.engine import run_validation
    from core.validator.contracts import Status, StatementType
    from core.validator.interfaces import FakeSchemaProvider

    schema = FakeSchemaProvider({
        "tables": [
            {"name": "users", "columns": {"id": "integer", "name": "varchar"}, "pk": ["id"], "row_count": 10}
        ]
    })

    # DESCRIBE
    res_desc = run_validation("DESCRIBE users", schema=schema, dialect="mysql")
    assert res_desc.status == Status.VALID
    assert res_desc.statement_type == StatementType.READ

    # EXPLAIN
    res_exp = run_validation("EXPLAIN SELECT id FROM users", schema=schema, dialect="postgres")
    assert res_exp.status == Status.VALID
    assert res_exp.statement_type == StatementType.READ

    # USE database
    res_use = run_validation("USE student_info", schema=schema, dialect="mysql")
    assert res_use.status == Status.VALID
    assert res_use.statement_type == StatementType.DDL
    assert not any(i.code in ("POLICY_01", "SCHEMA_01") for i in res_use.issues)

    # PRAGMA
    res_pragma = run_validation("PRAGMA table_info(users)", schema=schema, dialect="sqlite")
    assert res_pragma.status == Status.VALID
    assert res_pragma.statement_type == StatementType.READ


