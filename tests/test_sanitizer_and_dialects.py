def testSanitizerExtractsPositionalParametersForPostgreSql():
    raw_sql = "SELECT id, name FROM users WHERE age > 25 AND active = true;"
    stmt = sanitizeAndExtractParametersFromSqlAst(raw_sql, dialect="postgres")
    assert isinstance(stmt, ParameterizedStatement)
    assert len(stmt.params) >= 1
    assert "$1" in stmt.sql
    assert 25 in stmt.params

    # Check that legacy alias functions identically
    alias_stmt = sanitize_sql(raw_sql, dialect="postgres")
    assert alias_stmt == stmt


def testSanitizerExtractsQuestionMarkPlaceholdersForSqlite():
    raw_sql = "SELECT * FROM orders WHERE total > 100;"
    stmt = sanitizeAndExtractParametersFromSqlAst(raw_sql, dialect="sqlite")
    assert "?" in stmt.sql
    assert 100 in stmt.params


def testDialectConverterTransformsPostgreSqlAndMySqlStatements():
    raw_sql = "SELECT id, name FROM users LIMIT 10;"
    conv = convertSqlStatementToTargetDialects(raw_sql, target_dialects=["postgres", "mysql"])
    assert len(conv.conversions) == 2
    pg = conv.conversions[0]
    my = conv.conversions[1]
    assert pg.dialect == "postgres"
    assert my.dialect == "mysql"
    assert "LIMIT 10" in pg.sql

    # Check alias compatibility
    alias_conv = convert_sql(raw_sql, target_dialects=["postgres", "mysql"])
    assert alias_conv.original == conv.original


def testDialectConverterSupportsDirectSingleDialectConvenienceMethods():
    raw_sql = "SELECT id FROM users;"
    pg = convertSqlStatementToPostgreSqlDialect(raw_sql)
    assert isinstance(pg, DialectSQL)
    assert pg.dialect == "postgres"

    my = convertSqlStatementToMySqlDialect(raw_sql)
    assert my.dialect == "mysql"

    ora = convertSqlStatementToOracleDialect(raw_sql)
    assert ora.dialect == "oracle"

    ms = convertSqlStatementToMicrosoftSqlServerDialect(raw_sql)
    assert ms.dialect == "sqlserver"


