def testDialectConverterTranspilesIdentityToAutoIncrementForMySQLAndMariaDB():
    converter = DeterministicDialectConverter()
    sql = """
    CREATE TABLE students (
      student_id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
      name VARCHAR(100) NOT NULL,
      roll_number VARCHAR(10) NOT NULL
    );
    """
    res_mysql = converter.transpile(sql, target_dialect="mysql")
    assert "AUTO_INCREMENT" in res_mysql.compiled_query
    assert "GENERATED BY DEFAULT AS IDENTITY" not in res_mysql.compiled_query

    res_maria = converter.transpile(sql, target_dialect="mariadb")
    assert "AUTO_INCREMENT" in res_maria.compiled_query
    assert "GENERATED BY DEFAULT AS IDENTITY" not in res_maria.compiled_query


def testDialectConverterDeduplicatesColumnsInCreateTableForMySQL():
    converter = DeterministicDialectConverter()
    sql = """
    CREATE TABLE subjects (
      subject_id INT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
      subject_name VARCHAR(100) NOT NULL,
      subject_id INT NOT NULL,
      duration INT NOT NULL
    );
    """
    res = converter.transpile(sql, target_dialect="mysql")
    assert "AUTO_INCREMENT" in res.compiled_query
    # Check subject_id only appears once in column definitions
    assert res.compiled_query.count("subject_id") == 1


def testDialectConverterInjectsUseDatabaseAfterCreateDatabase():
    converter = DeterministicDialectConverter()
    sql = """
    CREATE DATABASE student_info;
    CREATE TABLE students (
      student_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
      name VARCHAR(100) NOT NULL
    );
    """
    res = converter.transpile(sql, target_dialect="mysql")
    assert "CREATE DATABASE student_info;" in res.compiled_query
    assert "USE `student_info`;" in res.compiled_query


def testMultiStatementValidationAllowsDDLWithSeedInserts():
    from core.validator.engine import run_validation
    from core.validator.contracts import Status, StatementType
    sql = """
    CREATE TABLE Students (
      StudentID INT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
      Name VARCHAR(100) NOT NULL,
      ConditionID INT,
      FOREIGN KEY (ConditionID) REFERENCES Conditions (ConditionID)
    );

    CREATE TABLE Conditions (
      ConditionID INT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
      ConditionName VARCHAR(100) NOT NULL
    );

    INSERT INTO Conditions (ConditionName)
    VALUES ('migraine'), ('diabetes'), ('pneumonia');
    """
    res = run_validation(sql, dialect="postgres")
    assert res.status == Status.VALID
    assert res.statement_type == StatementType.DDL
    assert "students" in res.tables_touched
    assert "conditions" in res.tables_touched
    assert not any(i.code == "PARSE_01" for i in res.issues)


